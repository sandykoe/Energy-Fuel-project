"""Import the reviewed workbook as a dated, read-only research snapshot.

Usage: python3 scripts/import_research_prices.py /path/Asia_Top50_Jet_Fuel_Prices.xlsx
Requires openpyxl only when importing a new workbook; normal builds are offline.
Excel formulas are retained alongside their cached values, never executed.
"""
import hashlib
import json
import sys
from pathlib import Path
import openpyxl

ROOT = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
book = openpyxl.load_workbook(source, data_only=True)
formulas = openpyxl.load_workbook(source, data_only=False)

def rows(sheet, first, last, columns):
    return [dict(sourceRow=row, **{key: book[sheet][f'{col}{row}'].value for col, key in columns.items()}) for row in range(first, last + 1)]

data = {
    'schemaVersion': 1, 'id': 'asia-top50-2026-11', 'revision': '2026-11-13-v1',
    'planningMonth': '2026-11', 'preparedOn': '2026-11-13',
    'classification': 'research_estimates', 'currency': 'USD', 'unit': 'USD/L',
    'densityKgPerL': 0.8,
    'source': {'filename': source.name, 'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
               'researchUrl': 'https://chatgpt.com/share/6af72b3d-1ef4-83ea-a11d-954a80152e07'},
    'airports': rows('Price estimates', 9, 58, {'A':'rank','B':'code','C':'name','D':'country','E':'passengersMillions2025','G':'low','H':'base','I':'high','J':'group','K':'evidence','L':'status'}),
    'calibrations': rows('Calibrations', 7, 16, {'A':'group','B':'low','C':'base','D':'high','F':'evidence','G':'expression','H':'method','I':'caveats','J':'sources','K':'airports'}),
    'inputs': rows('Inputs + method', 9, 55, {'A':'key','B':'parameter','C':'value','D':'unit','E':'period','F':'type','G':'source','H':'caveat'}),
    'observations': rows('Observations', 7, 44, {'A':'airport','B':'location','C':'period','D':'endDate','E':'originalValue','F':'unit','G':'sourceType','H':'usdPerL','I':'basis','J':'status','K':'eligibility','L':'source','M':'notes','N':'id'}),
    'traffic': rows('Traffic sources', 7, 56, {'A':'rank','B':'code','C':'name','D':'city','E':'country','F':'passengers2025','G':'year','H':'evidence','I':'source','J':'qualification','K':'status'}),
    'methodNotes': [book['Inputs + method'][f'J{row}'].value for row in range(62,72)],
    'formulas': {sheet.title: {cell.coordinate: cell.value for row in sheet for cell in row if cell.data_type == 'f'} for sheet in formulas},
}
assert len({r['code'] for r in data['airports']}) == 50
assert all(0 < r['low'] <= r['base'] <= r['high'] for r in data['airports'])
encoded = json.dumps(data, ensure_ascii=False, indent=2, allow_nan=False, default=str)
(ROOT / 'dist/data/research-prices.json').write_text(encoded + '\n')
(ROOT / 'dist/research-price-snapshot.js').write_text('/** Generated by scripts/import_research_prices.py; dated estimates, not quotations. */\nexport const RESEARCH_PRICES = ' + encoded + ';\n')
print('Imported 50 research estimates with observations, formulas, sources and assumptions.')
